List<String> _steps(PoseSeed seed) {
  if (seed.difficulty == 'difficult' || seed.difficulty == 'expert') {
    return [
      'Build the prerequisite mobility, strength and balance through a qualified teacher’s progression.',
      'Practise only the supported variation your teacher has assessed as appropriate for you.',
      'Keep the breath steady and exit with assistance before control is lost.',
    ];
  }
  return [
    'Begin from a stable ${seed.family.replaceAll('_', ' ')} position and settle your breathing.',
    'Move gradually toward the shape without forcing your range of motion.',
    'Keep the breath smooth and maintain a controlled, comfortable position.',
    'Exit slowly and pause before changing position.',
  ];
}

String _safety(String difficulty) => switch (difficulty) {
  'expert' => 'Expert-level pose. Do not attempt this pose from written instructions alone. Learn through supervised progression with a qualified yoga teacher.',
  'difficult' => 'This pose requires substantial mobility, strength, balance or inversion skill. Learn it progressively with a qualified yoga teacher.',
  _ => 'Work within a comfortable range, avoid forcing the shape, and stop if you feel pain, dizziness or loss of control.',
};

List<String> _sources(String difficulty) => switch (difficulty) {
  'beginner' => const ['AYUSH_CYP', 'YCB_YWI'],
  'intermediate' => const ['YCB_YWI', 'YCB_YM'],
  _ => const ['YCB_YM'],
};
