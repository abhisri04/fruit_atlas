def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def build():
    items = []
    for group, thing, about, start, where, care, display, steps in ITEMS:
        items.append({
            "id": f"collect_{slug(thing)}",
            "challenge_id": "start_a_collection",
            "name": f"Collect {thing[0].lower() + thing[1:]}",
            "category": thing,
            "filter_group": group,
            "difficulty": "beginner",
            "about": about,
            "howToSteps": steps,
            "tags": ["collecting", slug(group)],
            "keywords": [thing.lower(), "collecting", "collection"],
            "metadata": {
                "Start with": start,
                "Where to find": where,
                "Care": care,
                "Display idea": display,
            },
        })
    ids = [i["id"] for i in items]
    assert len(ids) == len(set(ids))
    OUT.write_text(json.dumps({"challenge_id": "start_a_collection", "version": 1,
                               "items": items}, ensure_ascii=False, indent=2) + "\n",
                   encoding="utf-8")
    print(OUT.name, len(items))


if __name__ == "__main__":
    build()
