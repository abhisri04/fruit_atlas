KIND_COUNTRY_NAMES = {"GB": "United Kingdom"}


def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def build():
    assert set(KINDS_OF) <= {n[0] for n in NUTS}, set(KINDS_OF) - {n[0] for n in NUTS}
    items = []
    for (name, aka, sci, kind, native, grown, states, find, tastes, taste, ways,
         shop_kinds, fact, safety, about) in NUTS:
        for code in native + grown:
            assert code in COUNTRIES, (name, code)
        assert kind in KINDS, name
        assert all(t in TASTES for t in tastes), name
        nut_id = f"nut_{slug(name)}"
        kinds = []
        for kname, code, kabout in KINDS_OF.get(name, []):
            assert code is None or code in COUNTRIES or code in KIND_COUNTRY_NAMES, (name, code)
            kinds.append({
                "id": f"{nut_id}__{slug(kname)}",
                "name": kname,
                "from": code,
                "from_name": None if code is None
                else (COUNTRIES[code][0] if code in COUNTRIES else KIND_COUNTRY_NAMES[code]),
                "description": kabout,
            })
        meta = {
            "Also called": ", ".join(aka) if aka else "",
            "Native to": ", ".join(COUNTRIES[c][0] for c in native),
            "Grown in": ", ".join(COUNTRIES[c][0] for c in grown),
            "Botanically": kind,
            "Taste": taste,
            "Where to find": find,
        }
        items.append({
            "id": nut_id,
            "challenge_id": "taste_world_nuts",
            "name": name,
            "category": kind,
            "filter_group": find,
            "scientific_name": sci,
            "about": about,
            "aliases": aka,
            "howToSteps": ways,
            "practiceSafety": safety,
            "keywords": [name.lower(), "nut"]
                        + [COUNTRIES[c][0].lower() for c in grown],
            "metadata": {k: v for k, v in meta.items() if v},
            "sub_items": [
                {"id": k["id"], "name": f"{k['name']} {name.lower()}",
                 "description": k["description"]}
                for k in kinds
            ],
            "nut": {
                "kind": kind,
                "native": native,
                "grown": grown,
                "india_states": states,
                "find": find,
                "tastes": tastes,
                "taste": taste,
                "ways": ways,
                "shop_kinds": None if kinds else shop_kinds,
                "kinds": kinds,
                "fact": fact,
                "safety": safety,
            },
        })
    ids = [i["id"] for i in items]
    assert len(ids) == len(set(ids)), ids
    used = sorted({c for n in NUTS for c in n[4] + n[5]})
    countries = {c: {"name": COUNTRIES[c][0], "continent": COUNTRIES[c][1]} for c in used}
    OUT.write_text(json.dumps({"challenge_id": "taste_world_nuts", "version": 1,
                               "countries": countries, "items": items},
                              ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(OUT.name, len(items), "nuts,", len(countries), "countries")


if __name__ == "__main__":
    build()
