def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def build():
    items = []
    for group, name, craft, level, time, need, win, about, steps in ITEMS:
        items.append({
            "id": f"make_{slug(name)}",
            "challenge_id": "make_something",
            "name": name,
            "category": craft,
            "filter_group": group,
            "difficulty": "beginner",
            "about": about,
            "howToSteps": steps,
            "tags": ["making", slug(group)],
            "keywords": [craft.lower(), "diy", "craft", "art"],
            "metadata": {
                "Level": level,
                "Time": time,
                "You'll need": need,
                "First win": win,
            },
        })
    ids = [i["id"] for i in items]
    assert len(ids) == len(set(ids))
    OUT.write_text(json.dumps({"challenge_id": "make_something", "version": 1, "items": items},
                              ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(OUT.name, len(items))


if __name__ == "__main__":
    build()
