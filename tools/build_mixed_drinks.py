def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def build():
    items = []
    for kind, drinks in (("Mocktail", MOCKTAILS), ("Cocktail", COCKTAILS)):
        for d in drinks:
            name = d["name"]
            assert d["country"] in COUNTRIES, name
            assert d["method"] in METHODS, name
            assert all(f in FLAVOURS for f in d["flavours"]), name
            ings = []
            for ing, qty, unit, label, opt in d["ings"]:
                assert ing in INGREDIENTS, (name, ing)
                ings.append({"id": ing, "qty": qty, "unit": unit,
                             "label": label or INGREDIENTS[ing][0].lower(),
                             "optional": opt})
            alcohol = any(INGREDIENTS[x["id"]][1] in ALCOHOL_GROUPS and not x["optional"]
                          for x in ings)
            if kind == "Mocktail":
                assert not alcohol or name == "Lemon, Lime & Bitters", name
                assert "zero" not in d, name
            else:
                assert alcohol and d.get("zero"), name
            spirit = None
            if kind == "Cocktail":
                spirit = next((SPIRIT_OF[x["id"]] for x in ings if x["id"] in SPIRIT_OF), "Other")
            country = COUNTRIES[d["country"]][0]
            drink_id = f"mix_{slug(name)}"
            meta = {
                "Also called": ", ".join(d.get("aka", [])),
                "Comes from": country,
                "Method": d["method"],
                "Glass": d["glass"],
                "Takes": f"{d['mins']} min",
                "You need": ", ".join(dict.fromkeys(
                    INGREDIENTS[x["id"]][0] for x in ings if not x["optional"])),
            }
            items.append({
                "id": drink_id,
                "challenge_id": CHALLENGE,
                "name": name,
                "category": kind,
                "filter_group": d["method"],
                "about": d["about"],
                "aliases": d.get("aka", []),
                "howToSteps": d["steps"],
                "practiceSafety": d.get("safety"),
                "keywords": [name.lower(), kind.lower(), country.lower()]
                            + [f.lower() for f in d["flavours"]],
                "metadata": {k: v for k, v in meta.items() if v},
                "drink": {
                    "type": kind,
                    "country": d["country"],
                    "spirit": spirit,
                    "method": d["method"],
                    "glass": d["glass"],
                    "minutes": d["mins"],
                    "flavours": d["flavours"],
                    "ingredients": ings,
                    "steps": d["steps"],
                    "garnish": d["garnish"],
                    "zero_proof": d.get("zero"),
                    "fact": d["fact"],
                    "safety": d.get("safety"),
                },
            })
    ids = [x["id"] for x in items]
    assert len(ids) == len(set(ids)), ids
    used = sorted({x["drink"]["country"] for x in items})
    out = {
        "challenge_id": CHALLENGE,
        "version": 1,
        "countries": {c: {"name": COUNTRIES[c][0], "continent": COUNTRIES[c][1]} for c in used},
        "ingredient_groups": GROUPS,
        "alcohol_groups": sorted(ALCOHOL_GROUPS),
        "ingredients": {k: {"name": v[0], "group": v[1]} for k, v in INGREDIENTS.items()},
        "items": items,
    }
    unused = set(INGREDIENTS) - {x["id"] for it in items for x in it["drink"]["ingredients"]}
    assert not unused, unused
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    mock = sum(1 for x in items if x["category"] == "Mocktail")
    print(OUT.name, len(items), "drinks:", mock, "mocktails,", len(items) - mock,
          "cocktails,", len(used), "countries")


if __name__ == "__main__":
    build()
